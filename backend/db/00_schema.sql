CREATE TABLE IF NOT EXISTS service_level_1 (
    code VARCHAR(20) PRIMARY KEY,
    original_code VARCHAR(20) NOT NULL,
    name TEXT NOT NULL,
    name_variants JSONB NOT NULL DEFAULT '[]'::jsonb,
    source_sheet TEXT NOT NULL,
    source_row INTEGER NOT NULL,
    source_range TEXT NOT NULL,
    transformations JSONB NOT NULL DEFAULT '{}'::jsonb,
    review_status VARCHAR(20) NOT NULL DEFAULT 'OK',
    sort_order INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    original_code VARCHAR(30) NOT NULL,
    level_1_code VARCHAR(20) NOT NULL REFERENCES service_level_1(code),
    name TEXT NOT NULL,
    active BOOLEAN,
    service_class TEXT,
    criticality TEXT,
    service_type TEXT,
    description TEXT,
    metric TEXT,
    minimum NUMERIC,
    maximum NUMERIC,
    review_status VARCHAR(20) NOT NULL DEFAULT 'OK',
    source_sheet TEXT NOT NULL,
    source_row INTEGER NOT NULL,
    source_range TEXT NOT NULL,
    transformations JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS import_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL,
    source_file TEXT NOT NULL,
    source_sha256 CHAR(64) NOT NULL,
    sheet_name TEXT NOT NULL,
    physical_rows INTEGER NOT NULL,
    created_count INTEGER NOT NULL DEFAULT 0,
    updated_count INTEGER NOT NULL DEFAULT 0,
    unchanged_count INTEGER NOT NULL DEFAULT 0,
    omitted_count INTEGER NOT NULL DEFAULT 0,
    observed_count INTEGER NOT NULL DEFAULT 0,
    level_1_count INTEGER NOT NULL DEFAULT 0,
    level_2_count INTEGER NOT NULL DEFAULT 0,
    summary JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS import_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_run_id BIGINT NOT NULL REFERENCES import_runs(id) ON DELETE CASCADE,
    severity VARCHAR(20) NOT NULL,
    reason VARCHAR(60) NOT NULL,
    code VARCHAR(30),
    message TEXT NOT NULL,
    source_sheet TEXT NOT NULL,
    source_range TEXT NOT NULL,
    source_row_start INTEGER,
    source_row_end INTEGER,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS catalog_import_control (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    sheet_name TEXT NOT NULL,
    physical_rows INTEGER NOT NULL,
    expected_level_1_count INTEGER NOT NULL,
    expected_level_2_count INTEGER NOT NULL,
    imported_level_1_count INTEGER NOT NULL,
    imported_level_2_count INTEGER NOT NULL,
    last_run_id BIGINT REFERENCES import_runs(id),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT catalog_import_level_1_control CHECK (expected_level_1_count = imported_level_1_count),
    CONSTRAINT catalog_import_level_2_control CHECK (expected_level_2_count = imported_level_2_count)
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    username_normalized VARCHAR(80) NOT NULL UNIQUE,
    email VARCHAR(320) NOT NULL UNIQUE,
    email_normalized VARCHAR(320) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    profile_encrypted TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_sessions (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,
    user_agent TEXT,
    ip_address INET
);

