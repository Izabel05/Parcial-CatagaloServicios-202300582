CREATE TABLE sd_demo_lotes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 semilla BIGINT NOT NULL, version TEXT NOT NULL, creado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(semilla,version)
);
CREATE TABLE sd_demo_tickets (
 lote_id BIGINT NOT NULL REFERENCES sd_demo_lotes(id),
 proceso TEXT NOT NULL, indice INTEGER NOT NULL CHECK(indice>0),
 ticket_id BIGINT NOT NULL UNIQUE REFERENCES sd_tickets(id),
 PRIMARY KEY(lote_id,proceso,indice)
);
