CREATE TABLE sd_ciclos_tiempo (
 ticket_id BIGINT NOT NULL REFERENCES sd_tickets(id), numero INTEGER NOT NULL CHECK(numero>0),
 inicio_at TIMESTAMPTZ NOT NULL, primera_atencion_at TIMESTAMPTZ,
 resuelto_at TIMESTAMPTZ, cerrado_at TIMESTAMPTZ,
 cola_objetivo_id BIGINT NOT NULL REFERENCES sd_colas(id),
 objetivo_atencion_min INTEGER CHECK(objetivo_atencion_min>0),
 objetivo_resolucion_min INTEGER CHECK(objetivo_resolucion_min>0),
 origen TEXT NOT NULL CHECK(origen IN ('nativo','migracion')),
 PRIMARY KEY(ticket_id,numero)
);
-- No se atribuyen objetivos históricos a tickets anteriores a esta migración.
INSERT INTO sd_ciclos_tiempo(ticket_id,numero,inicio_at,primera_atencion_at,resuelto_at,cerrado_at,cola_objetivo_id,origen)
 SELECT t.id,COALESCE(p.version,1),COALESCE(r.fecha,t.created_at),
 CASE WHEN t.primera_atencion_at>=COALESCE(r.fecha,t.created_at) THEN t.primera_atencion_at END,
 t.resuelto_at,t.cerrado_at,t.cola_id,'migracion'
 FROM sd_tickets t LEFT JOIN sd_procesos_ticket p ON p.ticket_id=t.id
 LEFT JOIN LATERAL (
  SELECT max(fecha) fecha FROM sd_historial h WHERE h.ticket_id=t.id AND h.accion='proceso'
  AND (h.despues->>'version')::int>(h.antes->>'version')::int
 ) r ON TRUE;
