ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK
 (role IN ('administrador','consulta','solicitante','agente','aprobador'));
CREATE TABLE sd_roles_usuario (
 usuario_id BIGINT NOT NULL REFERENCES users(id),
 rol TEXT NOT NULL CHECK(rol IN ('solicitante','agente','aprobador')),
 PRIMARY KEY(usuario_id,rol)
);
CREATE TABLE sd_colas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo TEXT NOT NULL UNIQUE, nombre TEXT NOT NULL, descripcion TEXT NOT NULL DEFAULT '',
 proceso TEXT NOT NULL CHECK(proceso IN ('nuevos_servicios','cambios','incidentes','eventos','problemas','accesos','servicios_tecnologia')),
 activo BOOLEAN NOT NULL DEFAULT TRUE, nivel_soporte INTEGER NOT NULL DEFAULT 1 CHECK(nivel_soporte BETWEEN 0 AND 4),
 ordenamiento TEXT NOT NULL DEFAULT 'prioridad_antiguedad' CHECK(ordenamiento='prioridad_antiguedad'),
 objetivo_primera_atencion_min INTEGER CHECK(objetivo_primera_atencion_min>0),
 objetivo_resolucion_min INTEGER CHECK(objetivo_resolucion_min>0)
);
CREATE TABLE sd_cola_responsables (
 cola_id BIGINT NOT NULL REFERENCES sd_colas(id), usuario_id BIGINT NOT NULL REFERENCES users(id),
 PRIMARY KEY(cola_id,usuario_id)
);
CREATE TABLE sd_permisos_cola (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cola_id BIGINT NOT NULL REFERENCES sd_colas(id), rol TEXT CHECK(rol IN ('administrador','consulta','solicitante','agente','aprobador')),
 usuario_id BIGINT REFERENCES users(id),
 permiso TEXT NOT NULL CHECK(permiso IN ('consultar','atender','transferir','aprobar','administrar')),
 CHECK((rol IS NULL) <> (usuario_id IS NULL)),
 UNIQUE NULLS NOT DISTINCT(cola_id,rol,usuario_id,permiso)
);
CREATE TABLE sd_tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero TEXT GENERATED ALWAYS AS ('SD-' || lpad(id::text,8,'0')) STORED UNIQUE,
 titulo TEXT NOT NULL, descripcion TEXT NOT NULL,
 solicitante_id BIGINT NOT NULL REFERENCES users(id), creador_id BIGINT NOT NULL REFERENCES users(id),
 servicio_id BIGINT NOT NULL REFERENCES services(id), cola_id BIGINT NOT NULL REFERENCES sd_colas(id),
 responsable_id BIGINT REFERENCES users(id),
 estado TEXT NOT NULL DEFAULT 'abierto' CHECK(estado IN ('abierto','en_atencion','resuelto','cerrado')),
 prioridad INTEGER NOT NULL DEFAULT 3 CHECK(prioridad BETWEEN 1 AND 4),
 impacto TEXT NOT NULL DEFAULT 'medio' CHECK(impacto IN ('bajo','medio','alto')),
 urgencia TEXT NOT NULL DEFAULT 'media' CHECK(urgencia IN ('baja','media','alta')),
 canal TEXT NOT NULL DEFAULT 'portal' CHECK(canal IN ('portal','telefono','correo','presencial','otro')),
 motivo_sin_ci TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 primera_atencion_at TIMESTAMPTZ, resuelto_at TIMESTAMPTZ, cerrado_at TIMESTAMPTZ,
 resolucion TEXT, CHECK(estado NOT IN ('resuelto','cerrado') OR length(trim(resolucion))>0)
);
CREATE TABLE sd_ticket_ci (
 ticket_id BIGINT NOT NULL REFERENCES sd_tickets(id), ci_id BIGINT NOT NULL REFERENCES cmdb_ci(id),
 PRIMARY KEY(ticket_id,ci_id)
);
CREATE TABLE sd_ticket_vinculos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 origen_id BIGINT NOT NULL REFERENCES sd_tickets(id), destino_id BIGINT NOT NULL REFERENCES sd_tickets(id),
 tipo TEXT NOT NULL CHECK(tipo IN ('relacionado','duplicado','incidente_problema','problema_cambio')),
 UNIQUE(origen_id,destino_id,tipo), CHECK(origen_id<>destino_id)
);
CREATE TABLE sd_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT REFERENCES sd_tickets(id), cola_id BIGINT REFERENCES sd_colas(id),
 actor_id BIGINT NOT NULL REFERENCES users(id), accion TEXT NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 antes JSONB, despues JSONB, interno BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE sd_comentarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES sd_tickets(id),
 actor_id BIGINT NOT NULL REFERENCES users(id), texto TEXT NOT NULL, interno BOOLEAN NOT NULL DEFAULT FALSE,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE sd_adjuntos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES sd_tickets(id),
 actor_id BIGINT NOT NULL REFERENCES users(id), nombre TEXT NOT NULL, mime TEXT NOT NULL,
 contenido BYTEA NOT NULL CHECK(octet_length(contenido) BETWEEN 1 AND 5242880),
 sha256 CHAR(64) NOT NULL, interno BOOLEAN NOT NULL DEFAULT FALSE,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE sd_aprobaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES sd_tickets(id),
 actor_id BIGINT NOT NULL REFERENCES users(id), aprobado BOOLEAN NOT NULL, motivo TEXT NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX sd_tickets_cola_orden ON sd_tickets(cola_id,prioridad,created_at,id);
CREATE INDEX sd_tickets_solicitante ON sd_tickets(solicitante_id,id);
CREATE INDEX sd_tickets_responsable ON sd_tickets(responsable_id,id);
CREATE INDEX sd_historial_ticket ON sd_historial(ticket_id,id);
CREATE INDEX sd_comentarios_ticket ON sd_comentarios(ticket_id,id);
CREATE INDEX sd_adjuntos_ticket ON sd_adjuntos(ticket_id,id);
-- Toda vía existente de administración respeta responsables de tickets abiertos.
CREATE FUNCTION sd_proteger_usuario_asignado() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.is_active IS FALSE OR NEW.role<>OLD.role) AND EXISTS
   (SELECT 1 FROM sd_tickets WHERE responsable_id=OLD.id AND estado<>'cerrado') THEN
   RAISE EXCEPTION 'Reasigne o cierre los tickets antes de desactivar o cambiar el rol del agente'
     USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER sd_usuario_asignado BEFORE UPDATE OF is_active,role ON users
 FOR EACH ROW EXECUTE FUNCTION sd_proteger_usuario_asignado();
