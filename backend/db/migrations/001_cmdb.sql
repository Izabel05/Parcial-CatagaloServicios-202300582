CREATE TABLE IF NOT EXISTS cmdb_clasificaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo TEXT UNIQUE NOT NULL, nombre TEXT NOT NULL,
 padre_id BIGINT REFERENCES cmdb_clasificaciones(id) ON DELETE RESTRICT,
 origen TEXT NOT NULL DEFAULT 'proyecto', referencia_fuente TEXT,
 activo BOOLEAN NOT NULL DEFAULT TRUE, CHECK (padre_id <> id)
);
CREATE TABLE IF NOT EXISTS cmdb_ubicaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo TEXT UNIQUE NOT NULL, nombre TEXT NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS cmdb_lotes_sinteticos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 semilla BIGINT NOT NULL, version TEXT NOT NULL,
 UNIQUE(semilla,version)
);
CREATE TABLE IF NOT EXISTS cmdb_ci (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo TEXT UNIQUE NOT NULL, nombre TEXT NOT NULL,
 clasificacion_id BIGINT NOT NULL REFERENCES cmdb_clasificaciones(id) ON DELETE RESTRICT,
 ubicacion_id BIGINT REFERENCES cmdb_ubicaciones(id) ON DELETE RESTRICT,
 responsable_usuario_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
 estado TEXT NOT NULL DEFAULT 'Activo', activo BOOLEAN NOT NULL DEFAULT TRUE,
 descripcion TEXT, numero_serie TEXT, version TEXT,
 fecha_adquisicion DATE, fecha_vencimiento DATE,
 ubicacion_original TEXT, responsable_original TEXT,
 nivel_seguridad TEXT, cumplimiento TEXT, estado_configuracion TEXT, numero_licencia TEXT,
 atributos_tecnicos JSONB NOT NULL DEFAULT '{}'::jsonb,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cmdb_dispositivos (
 ci_id BIGINT PRIMARY KEY REFERENCES cmdb_ci(id) ON DELETE RESTRICT,
 etiqueta TEXT UNIQUE NOT NULL,
 lote_id BIGINT REFERENCES cmdb_lotes_sinteticos(id) ON DELETE RESTRICT,
 indice_sintetico INTEGER,
 UNIQUE(lote_id,indice_sintetico),
 CHECK ((lote_id IS NULL) = (indice_sintetico IS NULL))
);
CREATE TABLE IF NOT EXISTS cmdb_tipos_relacion (
 codigo TEXT PRIMARY KEY, nombre TEXT NOT NULL,
 dirigida BOOLEAN NOT NULL, permite_ciclos BOOLEAN NOT NULL,
 propaga_dependencia BOOLEAN NOT NULL
);
INSERT INTO cmdb_tipos_relacion VALUES
 ('depende_de','Depende de',TRUE,FALSE,TRUE),
 ('alojado_en','Alojado en',TRUE,FALSE,TRUE),
 ('componente_de','Componente de',TRUE,FALSE,FALSE),
 ('conectado_a','Conectado a',FALSE,TRUE,FALSE)
ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS cmdb_relaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 origen_ci_id BIGINT NOT NULL REFERENCES cmdb_ci(id) ON DELETE RESTRICT,
 destino_ci_id BIGINT NOT NULL REFERENCES cmdb_ci(id) ON DELETE RESTRICT,
 tipo TEXT NOT NULL REFERENCES cmdb_tipos_relacion(codigo),
 justificacion TEXT NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE,
 created_by BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (origen_ci_id <> destino_ci_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS cmdb_relacion_activa
 ON cmdb_relaciones(origen_ci_id,destino_ci_id,tipo) WHERE activo;
CREATE TABLE IF NOT EXISTS cmdb_ci_servicios (
 ci_id BIGINT NOT NULL REFERENCES cmdb_ci(id) ON DELETE RESTRICT,
 servicio_id BIGINT NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 PRIMARY KEY(ci_id,servicio_id)
);
CREATE TABLE IF NOT EXISTS cmdb_auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entidad TEXT NOT NULL, entidad_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 accion TEXT NOT NULL, antes JSONB, despues JSONB,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS cmdb_ci_clase ON cmdb_ci(clasificacion_id);
CREATE INDEX IF NOT EXISTS cmdb_ci_ubicacion ON cmdb_ci(ubicacion_id);
CREATE INDEX IF NOT EXISTS cmdb_ci_responsable ON cmdb_ci(responsable_usuario_id);
CREATE INDEX IF NOT EXISTS cmdb_relacion_destino ON cmdb_relaciones(destino_ci_id) WHERE activo;
CREATE INDEX IF NOT EXISTS cmdb_auditoria_entidad ON cmdb_auditoria(entidad,entidad_id,id);
