CREATE TABLE sd_procesos_ticket (
 ticket_id BIGINT PRIMARY KEY REFERENCES sd_tickets(id),
 estado TEXT NOT NULL, datos JSONB NOT NULL DEFAULT '{}'::jsonb,
 version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
 servicio_resultado_id BIGINT REFERENCES services(id),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- El estado común se conserva; los registros previos deben completar sus evidencias.
INSERT INTO sd_procesos_ticket(ticket_id,estado)
 SELECT t.id,CASE WHEN t.estado IN ('resuelto','cerrado') THEN t.estado ELSE CASE q.proceso WHEN 'incidentes' THEN 'registro' WHEN 'eventos' THEN 'registro'
 WHEN 'problemas' THEN 'registro' ELSE 'solicitud' END END
 FROM sd_tickets t JOIN sd_colas q ON q.id=t.cola_id;
ALTER TABLE sd_aprobaciones ADD COLUMN version_proceso INTEGER;
CREATE UNIQUE INDEX sd_aprobacion_por_version ON sd_aprobaciones(ticket_id,version_proceso)
 WHERE version_proceso IS NOT NULL;
ALTER TABLE sd_ticket_vinculos DROP CONSTRAINT sd_ticket_vinculos_tipo_check;
ALTER TABLE sd_ticket_vinculos ADD CONSTRAINT sd_ticket_vinculos_tipo_check CHECK
 (tipo IN ('relacionado','duplicado','incidente_problema','problema_cambio','evento_incidente'));
CREATE TABLE sd_evento_incidente (
 evento_id BIGINT PRIMARY KEY REFERENCES sd_tickets(id),
 incidente_id BIGINT NOT NULL REFERENCES sd_tickets(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(evento_id<>incidente_id)
);
CREATE TABLE sd_notificaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evento_id BIGINT NOT NULL UNIQUE REFERENCES sd_tickets(id),
 incidente_id BIGINT NOT NULL REFERENCES sd_tickets(id),
 mensaje TEXT NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
