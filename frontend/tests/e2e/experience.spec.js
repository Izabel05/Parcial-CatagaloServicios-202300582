import {test,expect} from '@playwright/test'

async function login(page,user,password){
 await page.goto('/');await page.getByLabel('Usuario o correo').fill(user)
 await page.getByLabel('Contraseña',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Entrar',exact:true}).click()
 await page.getByRole('tab',{name:'Service Desk',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Service Desk',exact:true})).toBeVisible()
}

test('solicitante tiene portal propio, FAQ y tablero calendario',async({page})=>{
 test.skip(!process.env.E2E_REQUESTER_PASSWORD,'Requiere solicitante demo')
 await login(page,process.env.E2E_REQUESTER_USER,process.env.E2E_REQUESTER_PASSWORD)
 await expect(page.getByRole('heading',{name:'Portal del solicitante',exact:true})).toBeVisible()
 await expect(page.getByRole('region',{name:'Crear ticket',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Administración',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Consola del agente',exact:true})).toHaveCount(0)
 await page.getByRole('tab',{name:'FAQ',exact:true}).click()
 await page.getByLabel('Buscar en FAQ').fill('contraseñas')
 await page.getByRole('button',{name:'Buscar respuestas',exact:true}).click()
 await expect(page.getByText('Solicitar acceso',{exact:true})).toBeVisible()
 await page.getByText('Solicitar acceso',{exact:true}).click()
 await expect(page.getByRole('heading',{name:'¿Cómo solicito un permiso?'})).toBeVisible()
 await page.getByRole('tab',{name:'Tablero',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Tablero de atención'})).toBeVisible()
 await expect(page.getByText('tiempo calendario, 24 × 7',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Ámbito del tablero')).toHaveValue('propios')
 await expect(page.getByRole('heading',{name:'Tiempos y objetivos'})).toBeVisible()
 await page.screenshot({path:'test-results/tablero-solicitante.png',fullPage:true})
})

