test('administración publica FAQ sin mostrar borradores al autoservicio',async({page})=>{
 test.skip(!process.env.E2E_ADMIN_PASSWORD,'Requiere administrador demo')
 await login(page,process.env.E2E_ADMIN_USER,process.env.E2E_ADMIN_PASSWORD)
 await page.getByRole('button',{name:'Administración',exact:true}).click()
 const title=`FAQ-E2E-${Date.now()}`
 const admin=page.getByRole('region',{name:'Administración FAQ'})
 await admin.getByLabel('Título FAQ').fill(title)
 await admin.getByLabel('Pregunta FAQ').fill('¿Cómo consulto el servicio?')
 await admin.getByLabel('Respuesta FAQ').fill('Consulta el catálogo o crea una solicitud desde el portal.')
 await admin.getByRole('button',{name:'Guardar artículo FAQ'}).click()
 await expect(admin.getByRole('button',{name:`Editar ${title}`,exact:true})).toBeVisible()
 await page.getByRole('tab',{name:'FAQ',exact:true}).click()
 await page.getByLabel('Buscar en FAQ').fill(title)
 await page.getByRole('button',{name:'Buscar respuestas',exact:true}).click()
 await expect(page.getByText('No hay respuestas para esta búsqueda.',{exact:false})).toBeVisible()
 await page.getByRole('tab',{name:'Service Desk',exact:true}).click()
 await page.getByRole('button',{name:'Administración',exact:true}).click()
 await admin.getByRole('button',{name:`Editar ${title}`,exact:true}).click()
 await admin.getByLabel('Publicado en autoservicio').check()
 await admin.getByRole('button',{name:'Guardar artículo FAQ'}).click()
 await expect(admin.getByRole('status')).toHaveText('Artículo guardado')
 await page.getByRole('tab',{name:'FAQ',exact:true}).click()
 await page.getByLabel('Buscar en FAQ').fill(title)
 await page.getByRole('button',{name:'Buscar respuestas',exact:true}).click()
 await expect(page.getByText(title,{exact:true})).toBeVisible()
})

