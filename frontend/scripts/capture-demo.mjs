import {chromium, expect} from '@playwright/test'
import {mkdir, writeFile} from 'node:fs/promises'
import path from 'node:path'

const base=process.env.E2E_BASE_URL || 'http://127.0.0.1:15175'
const api=process.env.E2E_API_URL || 'http://127.0.0.1:18002'
const output=process.env.CAPTURE_DIR || '/evidence/capturas'
const browser=await chromium.launch()
const context=await browser.newContext({viewport:{width:1440,height:1000},locale:'es-GT',reducedMotion:'reduce'})
const page=await context.newPage()
const records=[]
let role='sin sesión'
await mkdir(output,{recursive:true})

async function capture(file,description,{fullPage=false,locator=null}={}) {
 await page.evaluate(()=>document.fonts.ready)
 const target=path.join(output,file)
 if(locator) await locator.screenshot({path:target,animations:'disabled'})
 else await page.screenshot({path:target,fullPage,animations:'disabled'})
 records.push({archivo:file,descripcion:description,rol:role,fecha_utc:new Date().toISOString(),viewport:page.viewportSize()})
}
async function login(kind) {
 const user=process.env[`E2E_${kind}_USER`],password=process.env[`E2E_${kind}_PASSWORD`]
 if(!user||!password)throw Error(`Faltan credenciales locales para ${kind}`)
 await page.goto(base)
 await page.evaluate(()=>sessionStorage.clear())
 await page.reload()
 await page.getByLabel('Usuario o correo',{exact:true}).fill(user)
 await page.getByLabel('Contraseña',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Entrar',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Servicios externos',exact:true})).toBeVisible()
 role=kind.toLowerCase()
}
async function tab(name) {
 await page.getByRole('tab',{name,exact:true}).click()
}
async function ticketsReady() {
 await expect(page.getByRole('region',{name:'Búsqueda de tickets'}).getByRole('button',{name:/^SD-\d+$/})).toHaveCount(25)
}
async function ticket(process,index) {
 await tab('Service Desk')
 await expect(page.getByRole('heading',{name:'Service Desk',exact:true})).toBeVisible()
 const filter=page.getByLabel('Número o título',{exact:true})
 const title=`[DEMO 202300582] ${process} ${String(index).padStart(2,'0')}`
 await filter.fill(title)
 await page.getByRole('button',{name:'Filtrar tickets',exact:true}).click()
 const region=page.getByRole('region',{name:'Búsqueda de tickets'})
 await expect(region.getByText(title,{exact:true})).toBeVisible()
 await expect(region.getByRole('button',{name:/^SD-\d+$/})).toHaveCount(1)
 await expect(region.getByRole('button',{name:/^SD-\d+$/})).toHaveCount(1)
 await region.getByRole('button',{name:/^SD-\d+$/}).click()
 const detail=page.getByRole('region',{name:'Ficha de ticket',exact:true})
 await expect(detail.getByRole('heading').first()).toContainText(title)
 await detail.scrollIntoViewIfNeeded()
 return detail
}
